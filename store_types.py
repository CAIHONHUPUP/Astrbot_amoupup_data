# -*- coding: utf-8 -*-
"""store_* mixin 组合后的公共接口（只给 mypy 看，运行时用 object 顶替）。"""
from __future__ import annotations

from typing import Any, Protocol


class StoreLike(Protocol):
    """DataStore 组合完成后的公共接口。

    3.0.0 起记忆主键升级到 pid，mixin 之间会互相调用（schema → people/memory、
    messages → cache），所以这些跨 mixin 的方法都必须在这里声明，否则 mypy 会报
    has no attribute。
    """

    _CN_NUM: Any
    _EXPORT_TABLES: Any
    _PERIODS: Any
    _emb_cache: Any
    _emb_failed: Any
    _emb_pending: Any
    _emb_pending_lock: Any
    _emb_queue: Any
    _emb_total: Any
    conn: Any
    lock: Any

    def setting(self, key, default=...): ...
    def get_profile(self, bot_id, uid): ...
    def save_profile(self, bot_id, uid, name=..., alias=..., relation=..., remark=...): ...
    def save_relation(self, bot_id, a_uid, b_uid, relation, note=...): ...
    def set_identity_alias(self, bot_id, platform, uid, alias_platform=..., alias_uid=...): ...
    # ---- 人物 / 身份（PeopleMixin）----
    def resolve_person(self, bot_id, platform, uid, name=..., auto_merge=...): ...
    def link_identity(self, bot_id, platform, uid, pid=..., name=...): ...
    def unlink_identity(self, bot_id, platform, uid): ...
    def merge_persons(self, bot_id, keep_pid, drop_pid): ...
    def repair_persons(self): ...
    def adopt_orphan_memories(self): ...
    def merge_ghost_persons(self): ...
    def pid_for_uid(self, bot_id, uid): ...
    def person_pid(self, bot_id, platform, uid): ...
    def canonical_uid(self, bot_id, platform, uid): ...
    def canonical_uid_for_uid(self, bot_id, uid): ...
    def clear_canonical_cache(self): ...
    def person_links(self, bot_id, pid): ...
    def person_context(self, bot_id, platform, uid, limit=...): ...
    # ---- 记忆（MemoryMixin）----
    def remember(self, bot_id, uid, content, kind=..., importance=..., scope=...,
                 group_id=..., subject=..., platform=..., idem_key=..., created_at=...,
                 last_hit_at=..., hit_count=..., keep_existing_content=...): ...
    def recall(self, bot_id, uid, query=..., limit=..., scope=..., group_id=...,
               platform=..., pid=..., half_life_days=..., importance_decay=...,
               pool_size=...): ...
    def list_memories(self, bot_id, uid=..., limit=..., pid=...): ...
    def delete_memory(self, bot_id, memory_id): ...
    def backfill_memory_platform(self, bot_id=..., window_sec=..., limit=..., apply=...): ...
    # ---- 缓存（LogsMixin）----
    def cache_get(self, bot_id, key): ...
    def cache_set(self, bot_id, key, value, ttl=...): ...
    def cache_delete(self, bot_id, key): ...
    # ---- 消息（MessagesMixin）----
    def add_message(self, bot_id, umo, uid=..., name=..., role=..., content=...,
                    platform=..., created_at=..., message_id=..., group_name=...): ...
    def list_messages(self, bot_id, umo=..., limit=..., pid=..., platform=..., uid=...,
                      kind=...): ...
    def list_messages_grouped(self, bot_id, umo=..., limit=..., pid=..., platform=...,
                              uid=..., summary_limit=..., kind=...): ...
    def group_sessions(self, bot_id, limit=...): ...
    def rename_group(self, bot_id, umo, name): ...
    def group_name_overrides(self, bot_id): ...
